import {writeFile, readdir, rm} from "node:fs/promises";
import {createHash} from "node:crypto";
import {fileURLToPath} from "node:url";
import path from "node:path";
import {gzipSync} from "node:zlib";
import {topology} from "topojson-server";

const root = fileURLToPath(new URL("./static/", import.meta.url));
const version = "v5.1.2";
const files = {}, retained = new Set();
for (const scale of ["110m", "50m", "10m"]) {
  const url = `https://raw.githubusercontent.com/nvkelso/natural-earth-vector/${version}/geojson/ne_${scale}_admin_0_countries.geojson`;
  const response = await fetch(url, {signal: AbortSignal.timeout(120000)});
  if (!response.ok) throw new Error(`Natural Earth ${scale}: HTTP ${response.status}`);
  const source = await response.json();
  if (source.type !== "FeatureCollection" || !source.features?.length) throw new Error("Missing country geometry");
  const countries = {type: "FeatureCollection", features: source.features.map(({geometry, properties}) => {
    if (!["Polygon", "MultiPolygon"].includes(geometry.type)) throw new Error("Unexpected country geometry");
    return {type: "Feature", id: properties.ADM0_A3, properties: {name: properties.ADMIN}, geometry};
  })};
  if (scale === "10m") {
    const identifiers = new Set(countries.features.map(item => item.id));
    for (const id of ["SGP", "MCO", "VAT", "SMR", "HKG"])
      if (!identifiers.has(id)) throw new Error(`Detailed atlas is missing ${id}`);
  }
  const data = topology({countries}, scale === "10m" ? 1e6 : 1e5);
  data.source = `${url} (Natural Earth ${version}, public domain)`;
  const bytes = Buffer.from(JSON.stringify(data) + "\n");
  const hash = createHash("sha256").update(bytes).digest("hex").slice(0, 12);
  const name = `world-${scale}-${hash}.json`;
  files[scale] = "/" + name;
  retained.add(name); retained.add(name + ".gz");
  await writeFile(path.join(root, name), bytes);
  const compressed = gzipSync(bytes, {level: 9});
  await writeFile(path.join(root, name + ".gz"), compressed);
  console.log(`${scale}: ${countries.features.length} shapes; ${compressed.length.toLocaleString()} compressed bytes`);
}
await writeFile(path.join(root, "atlas.mjs"),
  `// Generated by npm run build:atlas; URLs change when geometry changes.\nexport const MAP_FILES = Object.freeze(${JSON.stringify(files, null, 2)});\n`);
for (const name of await readdir(root)) {
  if (/^world-(110m|50m|10m)(-[a-f0-9]{12})?\.json(\.gz)?$/.test(name) && !retained.has(name))
    await rm(path.join(root, name));
}
