import {readFile, writeFile} from "node:fs/promises";
import {fileURLToPath} from "node:url";
import path from "node:path";
import {build} from "esbuild";

const root = fileURLToPath(new URL(".", import.meta.url));
await build({
  stdin: {
    contents: 'export {geoArea, geoCentroid, geoDistance, geoGraticule10, geoOrthographic, geoPath} from "d3-geo"; export {feature} from "topojson-client"; export {default as versor} from "versor";',
    resolveDir: root,
  },
  bundle: true,
  format: "esm",
  minify: true,
  outfile: path.join(root, "static", "geo-vendor.mjs"),
  banner: {js: "/* Generated by npm run build:map. Licenses: /geo-vendor-LICENSE.txt */"},
});
const licenses = await Promise.all(["d3-geo", "d3-array", "internmap", "versor", "topojson-client"].map(async name =>
  `${name}\n${await readFile(path.join(root, "node_modules", name, "LICENSE"), "utf8")}`));
await writeFile(path.join(root, "static", "geo-vendor-LICENSE.txt"), licenses.join("\n\n"));
